#!/usr/bin/env python3
"""Draws the paper's figures from the result files as TikZ, one paper/fig-*.tex each. Standard library only.

    python3 paper/figures.py

Series differ by lightness, dash and marker shape, and carry direct labels, so every figure reads in grayscale.
"""
import json
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
PAPER = ROOT / "paper"
summary = json.loads((RESULTS / "study-summary.json").read_text())
ARMS = {((a["L"], a["u"]), a["lr"], a["curriculum"]): a for a in summary["arms"]}
HI, LO = 0.003, 0.001
TILED = "uniform tiled"
INK = "black"
GRID = "black!18"
ENVELOPE = (0.735, 0.901)
HEADER = "% Generated by paper/figures.py from results/. Do not edit.\n"

SOLID = f"{INK}, line width=1.1pt"
DASHED = "black!72, line width=1.1pt, dash pattern=on 5pt off 2.5pt"
DOTTED = f"{INK}, line width=1.2pt, dash pattern=on 1.2pt off 2pt"
DASHDOT = "black!55, line width=1.1pt, dash pattern=on 6pt off 2pt on 1.2pt off 2pt"


def rows(name):
    return [json.loads(line) for line in (RESULTS / f"{name}.jsonl").read_text().splitlines() if line.strip()]


def path(points, style):
    coords = " -- ".join(f"({x:.3f},{y:.3f})" for x, y in points)
    return f"\\draw[{style}] {coords};\n"


def text(x, y, body, anchor="west", size="\\footnotesize", clear=False):
    fill = ", fill=white" if clear else ""
    return f"\\node[anchor={anchor}, inner sep=1.5pt, align=left, font={size}{fill}] at ({x:.3f},{y:.3f}) {{{body}}};\n"


def marker(x, y, shape, color=INK, filled=True):
    fill = color if filled else "white"
    if shape == "circle":
        return f"\\draw[{color}, fill={fill}, line width=0.7pt] ({x:.3f},{y:.3f}) circle (0.075);\n"
    if shape == "square":
        r = 0.068
        return f"\\draw[{color}, fill={fill}, line width=0.7pt] ({x - r:.3f},{y - r:.3f}) rectangle ({x + r:.3f},{y + r:.3f});\n"
    if shape == "triangle":
        r = 0.095
        return f"\\draw[{color}, fill={fill}, line width=0.7pt] ({x:.3f},{y + r:.3f}) -- ({x - r:.3f},{y - 0.8 * r:.3f}) -- ({x + r:.3f},{y - 0.8 * r:.3f}) -- cycle;\n"
    if shape == "diamond":
        r = 0.095
        return f"\\draw[{color}, fill={fill}, line width=0.7pt] ({x:.3f},{y + r:.3f}) -- ({x - r:.3f},{y:.3f}) -- ({x:.3f},{y - r:.3f}) -- ({x + r:.3f},{y:.3f}) -- cycle;\n"
    raise ValueError(shape)


def wrap(body):
    return HEADER + "\\begin{tikzpicture}\n" + body + "\\end{tikzpicture}\n"


def survival():
    width, height, low, high = 14.6, 4.3, 125, 8000
    X = lambda s: width * math.log(max(s, low) / low) / math.log(high / low)
    Y = lambda p: height * p
    out = ""
    for p in (0.25, 0.5, 0.75):
        out += path([(0, Y(p)), (width, Y(p))], f"{GRID}, line width=0.4pt")
    for s in (250, 500, 1000, 2000, 4000, 8000):
        out += path([(X(s), 0), (X(s), height)], f"{GRID}, line width=0.4pt")
        out += text(X(s), -0.03, str(s), "north")
    out += path([(0, height), (0, 0), (width, 0)], f"{INK}, line width=0.5pt")
    for p, label in ((0, "0"), (0.5, "0.5"), (1, "1")):
        out += text(-0.03, Y(p), label, "east")
    out += text(width / 2, -0.5, "Training step (log scale)", "north")
    out += f"\\node[rotate=90, anchor=south, font=\\footnotesize] at (-0.55,{height / 2:.3f}) {{Share of seeds with no event}};\n"
    series = [
        ("uniform tiled", SOLID, "circle"),
        ("bigram tiled", DASHED, "square"),
        ("bigram clone", DASHDOT, "triangle"),
        ("uniform clone", DOTTED, None),
    ]
    for name, style, shape in series:
        a = ARMS[((2, 2), HI, name)]
        points = [(0, Y(1))]
        survive = 1.0
        for step, s in a["curve"][1:]:
            points += [(X(step), Y(survive)), (X(step), Y(s))]
            survive = s
        points.append((X(a["budget"]), Y(survive)))
        out += path(points, style)
        if survive > 0:
            out += path([(X(a["budget"]), Y(survive) - 0.09), (X(a["budget"]), Y(survive) + 0.09)], f"{INK}, line width=0.8pt")
        if shape:
            out += marker(X(a["medianStep"]), Y(0.5), shape, "black!72" if name == "bigram tiled" else ("black!55" if name == "bigram clone" else INK))

    def label(name, x, y, anchor, title):
        a = ARMS[((2, 2), HI, name)]
        result = f"{a['events']} of {a['n']} seeds, median {a['medianStep']}" if a["medianStep"] else f"{a['events']} of {a['n']} seeds by step {a['budget']}"
        return text(x, y, f"{title}\\\\{result}", anchor, clear=True)

    out += label("uniform tiled", X(575) - 0.22, Y(0.31), "east", "Random, tiled")
    out += label("bigram tiled", X(1025) + 0.28, Y(0.66), "west", "Howe's language, tiled")
    out += label("bigram clone", X(7500) - 0.42, Y(0.27), "east", "Howe's language, clone rule")
    out += label("uniform clone", X(4000), Y(0.86), "east", "Random, clone rule")
    (PAPER / "fig-survival.tex").write_text(wrap(out))


def depth():
    height, low, high = 4.5, 400, 9000
    Y = lambda s: height * math.log(s / low) / math.log(high / low)
    unit = 2.95
    X0 = lambda d, left: left + unit * math.log2(d / 2)
    left_a, left_b = 0.0, 10.4
    out = ""
    for s in (500, 1000, 2000, 4000, 8000):
        out += path([(left_a, Y(s)), (left_a + 8.9, Y(s))], f"{GRID}, line width=0.4pt")
        out += path([(left_b, Y(s)), (left_b + 4.5, Y(s))], f"{GRID}, line width=0.4pt")
        out += text(left_a - 0.03, Y(s), str(s), "east")
    for left, span in ((left_a, 8.9), (left_b, 4.5)):
        out += path([(left, height), (left, 0), (left + span, 0)], f"{INK}, line width=0.5pt")
    for d in (2, 3, 4, 8, 12):
        out += text(X0(d, left_a), -0.03, str(d), "north")
    for d in (2, 3, 4):
        out += text(X0(d, left_b), -0.03, str(d), "north")
    out += text(left_a + 4.4, -0.5, "Layers applied (log scale)", "north")
    out += text(left_b + 2.2, -0.5, "Layers applied (log scale)", "north")
    out += text(left_a, height + 0.03, "lr 3e-3", "south west")
    out += text(left_b, height + 0.03, "lr 1e-3", "south west")
    out += f"\\node[rotate=90, anchor=south, font=\\footnotesize] at (-0.75,{height / 2:.3f}) {{Median event step (log scale)}};\n"

    def series(arms, lr, left, style, shape, color):
        body, points = "", []
        for arm in arms:
            a = ARMS[(arm, lr, TILED)]
            points.append((X0(arm[0], left), Y(a["medianStep"])))
        body += path(points, style)
        for arm, (x, y) in zip(arms, points):
            a = ARMS[(arm, lr, TILED)]
            lo_ci, hi_ci = a["ci"]
            body += path([(x, Y(lo_ci)), (x, Y(hi_ci))], f"{color}, line width=0.5pt")
            body += marker(x, y, shape, color)
        return body

    def median(arm, lr):
        return ARMS[(arm, lr, TILED)]["medianStep"]

    out += series([(2, 2), (3, 3), (4, 4), (8, 8), (12, 12)], HI, left_a, SOLID, "circle", INK)
    out += series([(2, 2), (4, 2), (8, 2)], HI, left_a, DASHED, "square", "black!72")
    out += series([(2, 1), (3, 1), (4, 1)], HI, left_a, DOTTED, "triangle", INK)
    out += series([(4, 4), (12, 4)], HI, left_a, DASHDOT, "diamond", "black!55")
    x8 = X0(8, left_a)
    out += path([(X0(4, left_a), Y(median((4, 1), HI))), (x8, Y(median((8, 1), HI)))], f"{INK}, line width=0.6pt, dash pattern=on 1pt off 3pt")
    long_arm = ARMS[((8, 1), HI, TILED)]
    out += path([(x8, Y(long_arm["ci"][0])), (x8, Y(long_arm["ci"][1]))], f"{INK}, line width=0.5pt")
    out += marker(x8, Y(long_arm["medianStep"]), "triangle", INK, filled=False)
    out += text(X0(12, left_a) + 0.1, Y(median((12, 12), HI)), f"untied\\\\{median((12, 12), HI)}", "west")
    out += text(x8 + 0.13, Y(median((8, 2), HI)) + 0.06, f"2 blocks, {median((8, 2), HI)}", "west")
    out += text(X0(4, left_a) - 0.1, Y(median((4, 1), HI)) + 0.22, f"1 block, {median((4, 1), HI)}", "east")
    out += text(x8 + 0.15, Y(median((8, 1), HI)) - 0.05, f"(8,1), {median((8, 1), HI)}\\\\no prefix signature", "west", clear=True)
    out += text(X0(12, left_a) + 0.1, Y(median((12, 4), HI)), f"(12,4)\\\\{median((12, 4), HI)}", "west")

    out += series([(2, 2), (3, 3), (4, 4)], LO, left_b, SOLID, "circle", INK)
    out += series([(2, 2), (4, 2)], LO, left_b, DASHED, "square", "black!72")
    out += series([(2, 1), (3, 1), (4, 1)], LO, left_b, DOTTED, "triangle", INK)
    x4 = X0(4, left_b)
    out += text(x4 + 0.12, Y(median((4, 4), LO)), f"untied\\\\{median((4, 4), LO)}", "west")
    out += text(x4 + 0.12, Y(median((4, 2), LO)), f"2 blocks\\\\{median((4, 2), LO)}", "west")
    out += text(x4 + 0.12, Y(median((4, 1), LO)), f"1 block\\\\{median((4, 1), LO)}", "west")
    (PAPER / "fig-depth.tex").write_text(wrap(out))


def median_of(values):
    ordered = sorted(values)
    mid = len(ordered) // 2
    return ordered[mid] if len(ordered) % 2 else (ordered[mid - 1] + ordered[mid]) / 2


def quartiles(values):
    ordered = sorted(values)

    def q(p):
        k = (len(ordered) - 1) * p
        i = int(k)
        return ordered[i] if i + 1 == len(ordered) else ordered[i] + (k - i) * (ordered[i + 1] - ordered[i])

    return q(0.25), q(0.75)


def gap():
    spec = (ROOT / "research/UPSTREAM-SPEC.md").read_text()
    table = [tuple(map(int, r)) for r in re.findall(r"^\| (\d+) \| (\d+) \| (\d+) \| (\d+) \| (\d+) \|$", spec, re.M)]
    howe = [r[2] / r[1] for r in table]
    config_a = rows("config-a")[0]
    third = json.loads((RESULTS / "third-summary.json").read_text())["spacing"]
    fine = [r["t_pv"] / r["t_event"] for r in rows("fine-2-2") if r["seed"] not in third["stoppedBeforeTheCoarseEvent"]]

    def arm(shape, lr, curriculum=TILED):
        g = ARMS[(shape, lr, curriculum)]["gap"]
        return g["median"], g["iqr"]

    groups = [
        ("Config A", [
            ("Howe's fleet", median_of(howe), quartiles(howe)),
            ("This trainer, one seed", config_a["t_pv"] / config_a["t_event"], None),
        ]),
        ("lr 3e-3, 25-step evals", [(str(s).replace(" ", ""), *arm(s, HI)) for s in [(2, 2), (3, 3), (4, 4), (4, 2), (2, 1), (3, 1), (4, 1)]]),
        ("lr 1e-3, 25-step evals", [(str(s).replace(" ", ""), *arm(s, LO)) for s in [(2, 2), (3, 3), (4, 4), (4, 2), (2, 1), (3, 1), (4, 1)]]),
        ("(2,2), same seeds", [
            ("5-step evals", median_of(fine), quartiles(fine)),
        ]),
        ("Deeper, lr 3e-3", [(str(s).replace(" ", ""), *arm(s, HI)) for s in [(8, 8), (12, 12), (8, 2), (12, 4), (8, 1)]]),
        ("Howe's language, (2,2)", [
            ("tiled", *arm((2, 2), HI, "bigram tiled")),
            ("clone", *arm((2, 2), HI, "bigram clone")),
        ]),
    ]
    row_h, left, width, low, high = 0.295, 5.15, 9.6, 0.1, 0.95
    X = lambda f: left + width * (f - low) / (high - low)
    total = sum(len(g[1]) for g in groups)
    gaps = len(groups) - 1
    top = row_h * (total + gaps * 0.55)
    out = f"\\fill[black!12] ({X(ENVELOPE[0]):.3f},0) rectangle ({X(ENVELOPE[1]):.3f},{top + 0.1:.3f});\n"
    for f in (0.2, 0.4, 0.6, 0.8):
        out += path([(X(f), 0), (X(f), top + 0.1)], f"{GRID}, line width=0.4pt")
        out += text(X(f), -0.03, f"{f:.1f}", "north")
    out += path([(left, 0), (left + width, 0)], f"{INK}, line width=0.5pt")
    out += text(left + width / 2, -0.42, "Anchor step over event step, median and interquartile range", "north")
    out += text(X(ENVELOPE[0]), top + 0.1, str(ENVELOPE[0]), "south")
    out += text(X(ENVELOPE[1]), top + 0.1, str(ENVELOPE[1]), "south")
    y = top - row_h * 0.5
    for title, items in groups:
        out += text(0, y, title, "west", "\\footnotesize")
        for label, value, iqr in items:
            out += text(left - 0.08, y, label, "east", "\\footnotesize")
            if iqr:
                out += path([(X(iqr[0]), y), (X(iqr[1]), y)], f"{INK}, line width=0.8pt")
            inside = ENVELOPE[0] <= value <= ENVELOPE[1]
            out += marker(X(value), y, "circle", INK, filled=inside)
            end = X(iqr[1]) if iqr else X(value)
            out += text(max(end, X(value)) + 0.12, y, f"{value:.3f}", "west", "\\scriptsize")
            y -= row_h
        y -= row_h * 0.55
    (PAPER / "fig-gap.tex").write_text(wrap(out))


if __name__ == "__main__":
    survival()
    depth()
    gap()
